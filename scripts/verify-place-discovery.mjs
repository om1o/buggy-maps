import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import {parseArea, encodeArea, rowsInArea} from '../dist/buggy/area-search.js';
import {mixedPlaceResults, exactSchool} from '../dist/buggy/place-search.js';
import {indexRow, findProperties} from '../dist/buggy/search.js';
import {mergeHomeRows} from '../dist/buggy/home-rows.js';

const data=new URL('../dist/buggy/data/',import.meta.url);
const json=async name=>JSON.parse(await readFile(new URL(name,data),'utf8'));
const base=JSON.parse(gunzipSync(await readFile(new URL('index.json.gz',data))));
const supplemental=await json('gallery-homes.json');
const homes=mergeHomeRows(base,supplemental.homes).map(row=>indexRow(row));
const schools=(await json('schools.json')).schools;
const exact=schools.find(school=>school.id==='fl-13-0841');
const filtered=rowsInArea(homes,parseArea('-80.26,25.7,-80.23,25.741'));
const sample=filtered.find(home=>home.id==='county-0141290000480');
assert.ok(sample);assert.ok(filtered.length>1 && filtered.length<homes.length);
assert.ok(rowsInArea(schools,parseArea('-80.26,25.7,-80.23,25.741')).includes(exact));
for (const invalid of [null,'','0,0,0,0','-81,25,-82,28','no,1,2,3','-181,25,-80,26','-81,25,-80,95'])assert.equal(parseArea(invalid),null);
const box=parseArea('-80.26,25.7,-80.23,25.741');
assert.deepEqual(parseArea(encodeArea(box)),box);
assert.deepEqual(rowsInArea([{id:1,lat:25.7,lng:-80.26},{id:2,lat:null,lng:-80.26},{id:3,lat:25.7,lng:-80.26,withheld:true}],box).map(x=>x.id),[1]);
const address=findProperties(homes,{},'3744 Stewart Ave');
assert.equal(mixedPlaceResults('3744 Stewart Ave',address,[exact],'schools')[0].row.id,sample.id);
assert.equal(mixedPlaceResults(exact.name,[sample],[exact],'homes')[0].row.id,exact.id);
assert.equal(exactSchool([exact], 'Coconut Grove Elementary').id,exact.id);
assert.equal(exactSchool([exact,{...exact,id:'other'}],exact.name),null);
const broad=mixedPlaceResults('33133',filtered,[exact],'homes');
assert.ok(broad.length<=6 && broad.some(x=>x.kind==='school') && broad.some(x=>x.kind==='home'));
console.log('Home and school ranking, ambiguous aliases, cross-mode addresses and inclusive map-area bounds verified against the full catalog.');
